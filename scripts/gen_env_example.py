"""Generate ``.env.example`` from the ``Settings`` model (the env contract).

Every field of ``ratchet.config.settings.Settings`` becomes one ``NAME=value`` line, preceded
by its description as a comment, in source order and grouped under the ``# --- Group ---``
comments of the class body. Values: a value already in ``.env.example`` wins (so hand-set
examples such as ``RATCHET_SIMULATE_ENABLED=true`` survive a regeneration), then
:data:`PINNED`, then the field default. Secrets are empty unless the file already had a
value; ``None`` is empty (or a commented-out ``# NAME=`` for an optional path or number,
which ``NAME=`` would mis-parse), booleans are lower case, dicts are JSON.

    uv run python scripts/gen_env_example.py          # rewrite .env.example
    uv run python scripts/gen_env_example.py --check  # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import textwrap
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

__all__ = ["ENV_EXAMPLE", "PINNED", "groups", "existing_values", "render", "main"]

ENV_EXAMPLE = ROOT / ".env.example"
SOURCE = ROOT / "ratchet" / "config" / "settings.py"

# Example values that differ from the field default on purpose (the example
# is a local dev host, where Simulate is on; the code default is off).
PINNED: dict[str, str] = {"RATCHET_SIMULATE_ENABLED": "true"}

HEADER = """\
# Ratchet environment contract. Copy to .env and fill in. Never commit .env.
# Every variable maps 1:1 to a field in ratchet/config/settings.py.
# Generated by scripts/gen_env_example.py from the Settings model: edit descriptions and
# defaults there, then run `uv run python scripts/gen_env_example.py`. Values already set
# in this file are kept when it is regenerated.
"""

_GROUP = re.compile(r"^\s{4}# --- (?P<name>.+?) -{3,}\s*$")
_FIELD = re.compile(r"^\s{4}(?P<name>[a-z][a-z0-9_]*)\s*:")
_LINE = re.compile(r"^(?P<key>[A-Z][A-Z0-9_]*)=(?P<value>.*)$")
_WIDTH = 96


def groups(source: Path = SOURCE) -> list[tuple[str, list[str]]]:
    """``[(group title, [field names])]`` in source order."""
    out: list[tuple[str, list[str]]] = []
    in_class = False
    for line in source.read_text(encoding="utf-8").splitlines():
        if line.startswith("class Settings("):
            in_class = True
            continue
        if in_class and line and not line.startswith(" "):
            break
        if not in_class:
            continue
        if match := _GROUP.match(line):
            out.append((match.group("name"), []))
        elif (match := _FIELD.match(line)) and out:
            out[-1][1].append(match.group("name"))
    return out


def existing_values(path: Path = ENV_EXAMPLE) -> dict[str, str]:
    """``NAME -> value`` for every assignment line already in ``path``."""
    if not path.is_file():
        return {}
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if (match := _LINE.match(line.strip())) and match.group("value"):
            values[match.group("key")] = match.group("value")
    return values


def _is_secret(annotation: object) -> bool:
    from pydantic import SecretStr

    return annotation is SecretStr or SecretStr in typing.get_args(annotation)


def _format(value: object) -> str:
    from pydantic import SecretStr

    if value is None or isinstance(value, SecretStr):
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, dict | list):
        return json.dumps(value, separators=(", ", ": "))
    if isinstance(value, Path):
        text = str(value)
        return text if value.is_absolute() or text.startswith(".") else f"./{text}"
    return str(value)


def _choices(annotation: object) -> list[str]:
    args = typing.get_args(annotation)
    if typing.get_origin(annotation) is typing.Literal:
        return [str(a) for a in args]
    for arg in args:
        if typing.get_origin(arg) is typing.Literal:
            return [str(a) for a in typing.get_args(arg)]
    return []


def _comment(description: str, choices: list[str]) -> list[str]:
    lines = textwrap.wrap(
        description.strip(), width=_WIDTH, initial_indent="# ", subsequent_indent="# "
    )
    if choices:
        lines.append(f"# One of: {' | '.join(choices)}")
    return lines


def _unset_line(annotation: object, default: object) -> bool:
    """An optional non-string field defaulting to ``None`` cannot be given as ``NAME=``
    (pydantic would parse ``""`` as a path or a number), so it is shown commented out."""
    if default is not None:
        return False
    inner = [a for a in typing.get_args(annotation) if a is not type(None)]
    return bool(inner) and not any(a is str or _is_secret(a) for a in inner)


def _section(title: str) -> str:
    head = f"# --- {title} "
    return head + "-" * max(3, _WIDTH - len(head))


def render(existing: dict[str, str] | None = None) -> str:
    """The full ``.env.example`` text."""
    from ratchet.config.settings import Settings

    existing = existing_values() if existing is None else existing
    fields = Settings.model_fields
    seen: set[str] = set()
    parts = [HEADER]
    for title, names in groups():
        lines = [_section(title)]
        for name in names:
            field = fields[name]
            key = name.upper()
            seen.add(name)
            if key in existing:
                value = existing[key]
            elif key in PINNED:
                value = PINNED[key]
            elif _is_secret(field.annotation):
                value = ""
            else:
                value = _format(field.get_default(call_default_factory=True))
            lines += _comment(field.description or "", _choices(field.annotation))
            unset = not value and _unset_line(field.annotation, field.default)
            lines.append(f"# {key}=" if unset else f"{key}={value}")
        parts.append("\n".join(lines) + "\n")
    missing = sorted(set(fields) - seen)
    if missing:
        raise SystemExit(f"Settings fields outside a '# ---' group: {', '.join(missing)}")
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    args = parser.parse_args(argv)
    text = render()
    current = ENV_EXAMPLE.read_text(encoding="utf-8") if ENV_EXAMPLE.is_file() else ""
    if args.check:
        if current != text:
            print(".env.example is out of date; run scripts/gen_env_example.py", file=sys.stderr)
            return 1
        return 0
    if current != text:
        ENV_EXAMPLE.write_text(text, encoding="utf-8")
        print(f"wrote {ENV_EXAMPLE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
